import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {placeEnglish} from '../src/v3r1/voice-placement.mjs';
const id=process.argv[2];
if(!process.argv.includes('--user-approved'))throw Error('Listening approval is required; candidate files remain separate');
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const candidates=read(process.argv.find(a=>a.endsWith('.json'))??'public/audio/v3r1/english-candidates.json');
const candidate=candidates.english_candidates.find(e=>e.take_id===id);
if(!candidate)throw Error('Unknown candidate');
const official=read('public/audio/v3/voices-manifest.json');
const sha=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
for(const e of official.voices)if(sha(e.output_file)!==candidates.preserved_v3_voice_hashes[e.output_file])throw Error('Original voice changed');
const timing=read('src/v3/voice-timing.json');
const text=candidates.text;
const en={...placeEnglish(candidate),selected_candidate:id,subjective_review:'User selected this audition in the current chat',reference_language:'en'};
const manifest={...official,version:'v3r1-user-selected',english_selection:{status:'user-approved',candidate:id},english_candidates:candidates.english_candidates,voices:[...official.voices.filter(e=>e.language!=='en'),en]};
timing.english_status='user-approved-'+id;
timing.en={frames:en.speech_end_frames,onset:en.speech_onset_frames,text,voice_start:en.start_frame,voice_end:en.end_frame,voice_file:en.output_file,voice_sha256:en.output_sha256,spoken_characters:en.character_markers,characters:Array.from(text,(character,i)=>({character,frame:1800+i*170/(text.length-1),method:'Independent subtitle reveal approved by user'}))};
writeFileSync('public/audio/v3r1/voices-manifest.json',JSON.stringify(manifest,null,2)+'\n');
writeFileSync('src/v3r1/voice-timing.json',JSON.stringify(timing,null,2)+'\n');
console.log(`Bound user-selected ${id}; original native recordings preserved`);
